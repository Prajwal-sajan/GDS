import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const src=fs.readFileSync('public/js/savetrip-visual.js','utf8');
const css=fs.readFileSync('public/css/savetrip-visual.css','utf8');
const html=fs.readFileSync('public/index.html','utf8');
const keys=['gds','fleet','sarathi','dailyops','crm','settings'];
const original=Object.fromEntries(keys.map(k=>[k,()=>{}]));
const sandbox={G:{screens:{...original}},esc:x=>String(x),console};
vm.runInNewContext(src,sandbox,{filename:'savetrip-visual.js'});
for(const key of keys) assert.notEqual(sandbox.G.screens[key],original[key],`${key} was not wrapped`);
for(const label of ['Cities & Schedule','Pickups','Drops','Breaks','Fares','Block','Cancellation','Expenses','History','Seat Layout','Amenities','Payables','Bank Details','Documents','Search rank','Needs action','All ratings','Not rated','Off','Own','Branch','Company','Fleet Map','Last engine data','Passenger Search']) assert.ok(src.includes(label),`missing ${label}`);
assert.ok(html.indexOf('/js/savetrip-visual.js')>html.indexOf('/js/fleet-operations-parity.js'));
assert.ok(html.indexOf('/js/savetrip-visual.js')<html.indexOf('/js/main.js'));
assert.ok(css.includes('.sv-workspace'));
assert.ok(src.includes('Backend action not connected'));
assert.ok(src.includes('UI draft stored locally'));
assert.ok(src.includes('not live optimization'));
console.log('PASS: screenshot-first UI overlay registered on six GDS screens; key popup/tab labels and safe demo boundaries present.');
