// Vendors the legacy communications / daily-ops / Sarathi screens verbatim into the React app.
// Output: modern/frontend/src/features/legacyScreens/vendor/screens.legacy.ts. Re-run after changing any listed legacy source.
// Patches (documented, minimal): core.js G.api/G.download are replaced by the runtime adapter (same legacy paths, served by the
// .NET API).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const out = join(root, "modern/frontend/src/features/legacyScreens/vendor/screens.legacy.ts");
const read = (f) => readFileSync(join(root, "public/js", f), "utf8");

let core = read("core.js");
const apiStart = core.indexOf("G.api = async function");
const apiEnd = core.indexOf("G.get = (u)");
if (apiStart < 0 || apiEnd < 0) throw new Error("core.js G.api block not found");
core = core.slice(0, apiStart) + "G.api = __rt.api;\n" + core.slice(apiEnd);
core = core.replace(/G\.download = async[^\n]*\n/, "G.download = __rt.download;\n");
const pub = "Object.assign(window, { esc, inr, num, pct, today, addDays, fdate, fdt, t12, can, $, $$, statusBadge });";
if (!core.includes(pub)) throw new Error("core.js window export line changed");


const files = ["ui-common.js", "ota-ratings-v44.js", "dailyops-parity-v12.js", "sarathi-parity-v12.js", "communication-history-v35.js", "communications-v14.js"];
const body = [`/* ===== public/js/core.js (G.api / G.download patched) ===== */\n${core}`,
  ...files.map((f) => `/* ===== public/js/${f} (verbatim) ===== */\n${read(f)}`)].join("\n");

const src = `// @ts-nocheck
/* eslint-disable */
// GENERATED by modern/scripts/vendor-legacy-screens.mjs — do not edit; edit the legacy public/js sources and re-run.
export interface LegacyRuntime { api(method: string, url: string, body?: unknown): Promise<any>; download(url: string, name: string): Promise<void> }
let __G: any;
export function legacyScreens(__rt: LegacyRuntime): any {
  if (__G) return __G;
${body}
  __G = G;
  return G;
}
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, src);
console.log("wrote", out, src.length, "bytes");
