#requires -Version 7
# Generates docs/modernization/API_PARITY_MATRIX.md from the legacy Express route declarations.
# Re-run after migrating endpoints; update $Mapped to record the modern equivalent.
$root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$files = @(Get-ChildItem "$root/server/api" -Filter *.js) + (Get-Item "$root/server/index.js")
$rx = [regex]'\.(get|post|put|patch|delete)\(\s*[''"`]([^''"`]+)[''"`]'
$rows = foreach ($f in $files) {
  $n = 0
  foreach ($line in Get-Content $f.FullName) {
    $n++
    foreach ($m in $rx.Matches($line)) {
      [pscustomobject]@{ Method = $m.Groups[1].Value.ToUpper(); Path = $m.Groups[2].Value; File = "server/$(if ($f.Name -eq 'index.js') {''} else {'api/'})$($f.Name)"; Line = $n }
    }
  }
}
# Legacy path prefix -> modern equivalent (only entries that are implemented AND tested).
$Mapped = [ordered]@{
  '^/trips/:sid/cancel$'      = 'PARTIAL|POST /api/admin/trips/{id}/cancel — full refund + RedBus MANUAL_BUS_CANCELLATION/REMOVE_SERVICE; legacy notification fan-out not yet ported'
  '^/bookings/:pnr/shift$'    = 'PARTIAL|POST /api/admin/bookings/{pnr}/shift — whole-PNR shift + RedBus SHIFT callback; legacy fare-difference handling not yet ported'
  '^/bookings/:pnr/cancel$'   = 'PARTIAL|Inventory CancelAsync (exposed to RedBus via /redbus/cancelticket); counter/agent channel UI not yet ported'
  '^/schedules/:id/seat-layout$' = 'PARTIAL|/redbus/seatlayout (OTA view); operator layout UI not yet ported'
  '^/schedules/:id/update-v51/sync-ota$' = 'PARTIAL|POST /api/admin/integrations/redbus/resync (outbox SEARCH + NEW_CITY_VSD)'
}
$out = [System.Text.StringBuilder]::new()
[void]$out.AppendLine("# Legacy → modern API parity matrix (generated)")
[void]$out.AppendLine("")
[void]$out.AppendLine("Generated by ``modern/scripts/gen-parity-matrix.ps1`` from Express route declarations. **Status legend:** ``MIGRATED`` = modern endpoint implemented with full behavioural parity and tests; ``PARTIAL`` = core behaviour implemented and tested in the modern stack but some legacy behaviour is not yet ported; ``LEGACY`` = served only by the Node app (must not be switched off). Legacy paths are relative to the Express mount point.")
[void]$out.AppendLine("")
$migrated = 0
$sorted = $rows | Sort-Object File, Line
[void]$out.AppendLine("| # | Method | Legacy path | Source | Status | Modern equivalent |")
[void]$out.AppendLine("|---|---|---|---|---|---|")
$i = 0
foreach ($r in $sorted) {
  $i++
  $hit = $Mapped.Keys | Where-Object { $r.Path -match $_ } | Select-Object -First 1
  $status = if ($hit) { $migrated++; $Mapped[$hit].Split('|')[0] } else { 'LEGACY' }
  $modern = if ($hit) { $Mapped[$hit].Split('|', 2)[1] } else { '' }
  [void]$out.AppendLine("| $i | $($r.Method) | ``$($r.Path)`` | $($r.File):$($r.Line) | $status | $modern |")
}
$summary = "**Totals:** $($sorted.Count) legacy routes; 0 fully migrated; $migrated partially covered; $($sorted.Count - $migrated) legacy-only."
$text = $out.ToString().Replace("| # | Method", "$summary`n`n| # | Method")
Set-Content -Path "$root/docs/modernization/API_PARITY_MATRIX.md" -Value $text -Encoding utf8
Write-Host $summary
