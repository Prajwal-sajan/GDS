// Vendors the legacy Team & access layers verbatim into the React app.
// Sources (load order as public/index.html): settings-parity.js, settings-complete.js, team-access-v26/v28/v29.js.
// Output: modern/frontend/src/features/settings/vendor/teamAccess.legacy.ts — a single installer that runs the legacy
// IIFEs against an injected G runtime (no window.G global). Re-run after changing the legacy sources.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const files = ["settings-parity.js", "settings-complete.js", "team-access-v26.js", "team-access-v28.js", "team-access-v29.js"];
const out = join(root, "modern/frontend/src/features/settings/vendor/teamAccess.legacy.ts");
const body = files.map((f) => `/* ===== public/js/${f} (verbatim) ===== */\n` + readFileSync(join(root, "public/js", f), "utf8")).join("\n");
const src = `// @ts-nocheck
/* eslint-disable */
// GENERATED by modern/scripts/vendor-team-access.mjs — do not edit; edit the legacy source and re-run.
export function installTeamAccess(G, esc, can, fdate) {
const window = new Proxy(globalThis, { get: (t, k) => k === "G" ? G : k === "can" ? can : (typeof t[k] === "function" && !/^[A-Z]/.test(String(k)) ? t[k].bind(t) : t[k]) });
${body}
return G.screens.settings;
}
`;
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, src);
console.log("wrote", out, src.length, "bytes");
